//! Output headers. Recognize the comment estrogen emits, not a package name
//! that happens to occur in a string or an import.

use crate::format::MARKER;

const LEGACY: &str = "__FRX_OBF__";

fn matches_header(body: &str) -> bool {
    let body = body.trim();
    body == LEGACY || body.strip_suffix('/').unwrap_or(body) == MARKER
}

fn bom_end(source: &str) -> usize {
    source
        .strip_prefix('\u{feff}')
        .map_or(0, |_| '\u{feff}'.len_utf8())
}

/// Keep the BOM and the interpreter line ahead of any inserted JavaScript.
pub(crate) fn js_start(source: &str) -> usize {
    let bom = bom_end(source);
    let text = &source[bom..];
    if !text.starts_with("#!") {
        return bom;
    }
    text.find(['\r', '\n', '\u{2028}', '\u{2029}'])
        .map_or(source.len(), |at| {
            let ending = &text[at..];
            bom + at
                + if ending.starts_with("\r\n") {
                    2
                } else {
                    ending.chars().next().unwrap().len_utf8()
                }
        })
}

pub(crate) fn marked_js(source: &str) -> bool {
    source[js_start(source)..]
        .trim_start()
        .strip_prefix("/*")
        .and_then(|s| s.split_once("*/"))
        .is_some_and(|(body, _)| matches_header(body))
}

/// An XML declaration, when present, must remain the first thing in the SVG.
pub(crate) fn markup_start(source: &str, svg: bool) -> usize {
    let bom = bom_end(source);
    let trimmed = source[bom..].trim_start();
    if svg
        && trimmed
            .get(..5)
            .is_some_and(|s| s.eq_ignore_ascii_case("<?xml"))
    {
        if let Some(end) = trimmed.find("?>") {
            return source.len() - trimmed.len() + end + 2;
        }
    }
    bom
}

pub(crate) fn marked_markup(source: &str, svg: bool) -> bool {
    source[markup_start(source, svg)..]
        .trim_start()
        .strip_prefix("<!--")
        .and_then(|s| s.split_once("-->"))
        .is_some_and(|(body, _)| matches_header(body))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn recognizes_headers_not_text_in_the_body() {
        assert!(marked_js(
            "#!/usr/bin/env node\r\n/* generated by https://estro.help */ var x;"
        ));
        assert!(marked_js("\u{feff}/*__FRX_OBF__*/var x;"));
        assert!(marked_js("/* generated by https://estro.help/ */ var x;"));
        assert!(!marked_js(
            "const note = 'generated by https://estro.help';"
        ));
        assert!(!marked_js("const example = '/*__FRX_OBF__*/';"));
        assert!(marked_markup(
            "<?xml version='1.0'?><!--__FRX_OBF__--><svg/>",
            true
        ));
        assert!(!marked_markup("<p>Use @sysce/estrogen</p>", false));
    }
}
