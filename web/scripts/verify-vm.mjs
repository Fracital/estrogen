// Check the site VM entry emitted by Astro and compare it with its source in
// Node. A fallback fails the build instead of silently shipping.
import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
import { runInNewContext } from 'node:vm';

const html = readFileSync(new URL('../dist/index.html', import.meta.url), 'utf8');
const entry = [...html.matchAll(/<script\b([^>]*)>/gi)].find((match) =>
	/\bdata-vm-site\b/.test(match[1]),
);
assert.ok(entry, 'the page must load the VM site entry');

const src = /\bsrc=(?:"([^"]+)"|'([^']+)'|([^\s>]+))/.exec(entry[1]);
assert.ok(src, 'the VM script must have a src URL');
const asset = src[1] || src[2] || src[3];
assert.match(asset, /^\/_astro\/[A-Za-z0-9_-]+\.js$/, 'expected a hashed JS asset');

const code = readFileSync(new URL('../dist' + asset, import.meta.url), 'utf8');
const source = readFileSync(new URL('../src/scripts/site-runtime.js', import.meta.url), 'utf8');
assert.ok(
	code.startsWith('/* generated by https://estro.help */'),
	'the site entry was not transformed',
);
assert.ok(code.includes('JSON.parse('), 'the site entry fell back from the VM');

function observe(script, age, missingElement = false) {
	const now = Date.parse('2026-11-20T18:00:00Z');
	const iso = new Date(now - age).toISOString();
	const ago = { textContent: '' };
	const intervals = [];
	const serviceWorkerPaths = [];
	const loadEvents = [];
	class ClockDate extends Date {
		static now() {
			return now;
		}
	}
	const document = {
		getElementById(id) {
			if (id === 'buildTime') return { getAttribute: () => iso };
			if (id === 'buildAgo' && !missingElement) return ago;
			return null;
		},
	};
	const window = {
		setInterval(callback, delay) {
			intervals.push({ callback, delay });
		},
		addEventListener(name, callback) {
			loadEvents.push({ name, callback });
		},
	};
	const navigator = {
		serviceWorker: {
			register(path) {
				serviceWorkerPaths.push(path);
				return { catch() {} };
			},
		},
	};
	runInNewContext(
		script,
		{
			document, window, navigator, Date: ClockDate, Math, Number, atob,
			Uint8Array, TextDecoder,
		},
		{ timeout: 5000 },
	);
	for (const { name, callback } of loadEvents) {
		if (name === 'load') callback();
	}
	return {
		text: ago.textContent,
		intervals: intervals.map(({ delay }) => delay),
		serviceWorkerPaths,
	};
}

for (const age of [
	0,
	70_000,
	12 * 60_000,
	3 * 60 * 60_000,
	2 * 24 * 60 * 60_000,
	90 * 24 * 60 * 60_000,
	2 * 365 * 24 * 60 * 60_000,
]) {
	assert.deepEqual(
		observe(code, age),
		observe(source, age),
		'VM build clock changed runtime behavior',
	);
}
assert.deepEqual(
	observe(code, 0, true),
	observe(source, 0, true),
	'the VM build clock changed missing-element behavior',
);
assert.equal(observe(code, 0).text, '(just now)');
assert.deepEqual(observe(code, 0).serviceWorkerPaths, ['/sw.js']);
console.log('VM site entry: bytecode confirmed and Node behavior matches source');

const chunks = readdirSync(new URL('../dist/_astro/', import.meta.url))
	.filter((name) => name.endsWith('.js'))
	.map((name) => {
		const body = readFileSync(new URL('../dist/_astro/' + name, import.meta.url), 'utf8');
		return {
			name,
			bytes: Buffer.byteLength(body),
			kind: body.includes('JSON.parse(') &&
				body.startsWith('/* generated by https://estro.help */')
				? 'vm'
				: body.startsWith('/* generated by https://estro.help */')
					? 'fallback'
					: 'unchanged',
		};
	});
const vmChunks = chunks.filter((item) => item.kind === 'vm');
const fallbackChunks = chunks.filter((item) => item.kind === 'fallback');
const totalBytes = chunks.reduce((total, item) => total + item.bytes, 0);
const vmBytes = vmChunks.reduce((total, item) => total + item.bytes, 0);
console.log(
	`VM coverage: ${vmChunks.length}/${chunks.length} JS assets, ${vmBytes}/${totalBytes} bytes. ${fallbackChunks.length} literal-pool fallbacks.`,
);
if (process.env.ESTROGEN_REQUIRE_FULL_VM === '1') {
	assert.deepEqual(
		chunks.filter((item) => item.kind !== 'vm').map((item) => item.name),
		[],
		'full VM mode requires every emitted JS asset to compile as bytecode',
	);
}
